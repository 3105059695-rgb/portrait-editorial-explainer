/** A free layout in the same logical units as the 544-wide SVG stage.
 * Nodes keep their identities while their properties change. The author decides
 * the interface, content, state sequence, and camera route for each episode.
 */
export interface UINode {
  id: string;
  type: 'panel' | 'text' | 'button' | 'input' | 'badge' | 'image' | 'progress' | 'line' | 'chart' | 'cursor';
  x: number;
  y: number;
  w: number;
  h: number;
  text?: string;
  image?: string;
  fill?: string;
  color?: string;
  stroke?: string;
  radius?: number;
  fontSize?: number;
  weight?: number;
  opacity?: number;
  rotation?: number;
  /** Normalized progress, chart/line reveal, or cursor click phase, from 0 to 1. */
  value?: number;
  /** Supplied chart data; no synthetic series is generated by the renderer. */
  points?: number[];
  /** Space-separated visual modifiers, such as selected, primary, muted, or contain. */
  emphasis?: string;
}

export interface UIFrame {
  /** Local scene time in seconds, when these properties reach this state. */
  at: number;
  set: Partial<UINode>;
  ease?: 'smooth' | 'out' | 'linear';
}

export interface UITrack {
  nodeId: string;
  frames: UIFrame[];
}

export interface UICameraFrame {
  at: number;
  /** Look-at point in the authored canvas, not a translation offset. */
  x: number;
  y: number;
  scale: number;
}

export interface UIPlan {
  nodes: UINode[];
  tracks: UITrack[];
  camera?: UICameraFrame[];
  /** Defaults to 720. For 1080x1920 portrait layouts, author around 967.111. */
  canvasHeight?: number;
  showTitle?: boolean;
  /** A disclosure for illustrative UI. Defaults to 示意界面. */
  label?: string;
}
